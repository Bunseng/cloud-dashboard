import { clsx, type ClassValue } from "clsx";
import { twMerge } from "tailwind-merge";

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs));
}

/* "My Web App" -> "my-web-app" — used to derive a Host Name from a
   Service Name as the user types, without ever producing an invalid
   hostname segment (leading/trailing/duplicate hyphens). */
export function slugify(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
